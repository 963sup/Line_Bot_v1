/**
 * ============================================================================
 * 第一性原理分析：基礎設施伺服端環境屏障 (Server Environment Boundary)
 * ============================================================================
 *
 * 1. 根本問題 (Root Problem):
 *    在 Next.js 等全端混編專案中，開發者極易因路徑失誤將包含私鑰、
 *    C++ 原生模組 (`node:sqlite`) 或 Secret Manager 的伺服端適配器打包進入瀏覽器客戶端 Bundle，
 *    造成機密洩漏或執行期難以定位的語法崩潰。
 *
 * 2. 核心公理 (Core Axiom):
 *    - 【環境隔離公理 (Fail-Fast Boundary Guard)】：
 *      在模組載入時立即檢測 `window` 物件。凡在瀏覽器環境執行，立即中斷執行並拋出異常，
 *      確保伺服端依賴永遠無法在客戶端靜默執行。
 * ============================================================================
 */

// 伺服端適配器若被客戶端意外引用，立即快速失敗 (Fail-Fast)
if (typeof window !== "undefined") {
  throw new Error("Infrastructure adapters may only run on the server.");
}

export {};
