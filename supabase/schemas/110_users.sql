create table app_private."user_management_commands" (
  "actor" text not null,
  "request_id" uuid not null,
  "target" text not null,
  "fingerprint" text not null,
  "action" text not null,
  "reason" text not null,
  "previous_status" text not null,
  "status" text not null,
  "version" integer not null,
  "at" bigint not null,
  "result" jsonb not null,
  constraint "user_management_commands_pkey" PRIMARY KEY (actor, request_id),
  constraint "user_management_commands_action_check" CHECK ((action = ANY (ARRAY['suspend'::text, 'unsuspend'::text]))),
  constraint "user_management_commands_reason_check" CHECK (((length(reason) >= 1) AND (length(reason) <= 500))),
  constraint "user_management_commands_actor_fkey" FOREIGN KEY (actor) REFERENCES app_private.users(id),
  constraint "user_management_commands_target_fkey" FOREIGN KEY (target) REFERENCES app_private.users(id)
);
CREATE INDEX user_management_history ON app_private.user_management_commands USING btree (target, at DESC, request_id);
alter table app_private."user_management_commands" enable row level security;
revoke all on app_private."user_management_commands" from public, anon, authenticated, line_app;
grant insert, select on app_private."user_management_commands" to line_app;
create policy "backend_insert" on app_private."user_management_commands" as permissive for insert to "line_app" with check (true);
create policy "backend_read" on app_private."user_management_commands" as permissive for select to "line_app" using (true);

CREATE OR REPLACE FUNCTION app_private.track_user_status()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'app_private', 'pg_catalog'
AS $function$
begin
 new.status_version := old.status_version;
 new.suspended_from := old.suspended_from;
 if new.status is distinct from old.status then
  new.status_version := old.status_version+1;
  new.suspended_from := case when new.status='suspended' then old.status else null end;
 end if;
 return new;
end $function$;
revoke all on function app_private."track_user_status"() from public, anon, authenticated, line_app;
grant execute on function app_private."track_user_status"() to line_app;
CREATE TRIGGER user_status_version BEFORE UPDATE ON app_private.users FOR EACH ROW EXECUTE FUNCTION app_private.track_user_status();

