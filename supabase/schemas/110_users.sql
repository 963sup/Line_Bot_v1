-- User lifecycle, management history and user-owned triggers.

create table app_private."users" (
  "id" text not null,
  "auth_user_id" uuid,
  "status" text not null,
  "createdAt" bigint not null,
  "status_version" integer default 1 not null,
  "suspended_from" text,
  "account_kind" text generated always as ('USER'::text) stored,
  constraint "users_pkey" PRIMARY KEY (id),
  constraint "users_auth_user_id_key" UNIQUE (auth_user_id),
  constraint "users_status_check" CHECK ((status = ANY (ARRAY['paused'::text, 'active'::text, 'suspended'::text]))),
  constraint "users_status_version_check" CHECK ((status_version > 0)),
  constraint "users_suspended_from_check" CHECK ((suspended_from = ANY (ARRAY['active'::text, 'paused'::text]))),
  constraint "users_auth_user_id_fkey" FOREIGN KEY (auth_user_id) REFERENCES auth.users(id) ON DELETE RESTRICT,
  constraint "users_account_identity_fkey" FOREIGN KEY (id, account_kind) REFERENCES app_private.accounts(id, kind)
);
alter table app_private."users" enable row level security;
revoke all on app_private."users" from public, anon, authenticated, line_app;
grant insert, select, update on app_private."users" to line_app;
create policy "backend" on app_private."users" as permissive for all to "line_app" using (true) with check (true);

-- The existing registration/import path creates the identity in the same transaction.
-- No parallel Account writer or second ID allocation is introduced during expansion.
create function app_private.ensure_user_identity()
returns trigger
language plpgsql
set search_path to 'app_private', 'pg_catalog'
as $function$
begin
  if tg_op = 'DELETE' then
    raise exception 'user_identity_immutable' using errcode = '23514';
  end if;
  if tg_op = 'UPDATE' then
    if new.id is distinct from old.id or new."createdAt" is distinct from old."createdAt" then
      raise exception 'user_identity_immutable' using errcode = '23514';
    end if;
    return new;
  end if;
  insert into app_private.accounts(id, kind, created_at)
    values (new.id, 'USER', new."createdAt") on conflict (id) do nothing;
  if not exists (
    select 1 from app_private.accounts
    where id = new.id and kind = 'USER' and created_at = new."createdAt"
  ) then
    raise exception 'user_identity_mismatch' using errcode = '23514';
  end if;
  return new;
end
$function$;
revoke all on function app_private.ensure_user_identity() from public, anon, authenticated, line_app;
grant execute on function app_private.ensure_user_identity() to line_app;
create trigger user_identity
before insert or update or delete on app_private.users
for each row execute function app_private.ensure_user_identity();


